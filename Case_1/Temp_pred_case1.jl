#Defining the neural network
U = Lux.Chain(Lux.Dense(3,20,tanh),Lux.Dense(20,1))
rng = StableRNG(1111)
_para,st = Lux.setup(rng,U)
const _st_ = st

#Defining the UDE model
function UDE_model!(du,u,p,t,T∞,I_func)

    Cbat = 5*3600
    I = I_func(t)
    du[1] = -I/Cbat

    C₁ = -0.00153
    C₂ = 0.020306 #Thermal parameters

    G = (U([u[1],u[2],I],p,_st_)[1][1])^2 # The heat generated by the battery cell

    du[2] = (C₁*(u[2]-T∞)) + (C₂*G) # The lumped thermal model of the battery cell

end

UDE_model1!(du,u,p,t) = UDE_model!(du,u,p,t,T∞1,I1)
UDE_model2!(du,u,p,t) = UDE_model!(du,u,p,t,T∞2,I2)
UDE_model3!(du,u,p,t) = UDE_model!(du,u,p,t,T∞3,I3)
UDE_model4!(du,u,p,t) = UDE_model!(du,u,p,t,T∞4,I4)
UDE_model5!(du,u,p,t) = UDE_model!(du,u,p,t,T∞5,I5)
UDE_model6!(du,u,p,t) = UDE_model!(du,u,p,t,T∞6,I6)

# Defining the ODE problems for each dataset
prob1 = ODEProblem(UDE_model1!,[SOC1_0,T∞1],(t1[1],t1[end]),_para)
