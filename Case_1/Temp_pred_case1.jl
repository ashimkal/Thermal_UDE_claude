function condition_label(crate, temp)
    c = replace(crate, "p" => ".")  # "0p5C" → "0.5C", "1C" → "1C"
    c = replace(c, "C" => " C")     # "1 C", "0.5 C"
    return "$(c), $(temp)°C"
end

